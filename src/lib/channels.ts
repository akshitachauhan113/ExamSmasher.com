const normalized = TRUSTED_CHANNELS.map((c) =>
  c
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim(),
);

export function isTrustedChannel(channelTitle: string): boolean {
  const c = (channelTitle || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!c) return false;
  return normalized.some((t) => t.length > 2 && (c.includes(t) || t.includes(c)));
}
