import type { Topic, TopicResult } from "./types";

/**
 * Export helpers.
 *
 * These used to export ranked YouTube videos with channels, lengths and
 * scores. There is no YouTube API any more, so there are no titles, lengths or
 * scores to export — only the honest thing we do have: a link to YouTube's own
 * results page, built from the student's syllabus.
 */

type StudiedPredicate = (title: string) => boolean;

function linksFor(result: TopicResult | undefined): NonNullable<TopicResult["searches"]> {
  return result?.searches ?? [];
}

export function buildMarkdown(
  subject: string,
  topics: Topic[],
  results: Record<string, TopicResult>,
  isStudied: StudiedPredicate = () => false,
): string {
  const lines: string[] = [];
  const withLinks = topics.filter((t) => linksFor(results[t.id]).length > 0).length;
  const doneCount = topics.filter((t) => isStudied(t.title)).length;
  const left = topics.length - doneCount;

  lines.push(`# 📚 ${subject} — Study list`);
  lines.push("");
  lines.push(
    `> ${withLinks}/${topics.length} topics have a search link · ${doneCount}/${topics.length} already studied · ${left} to go · generated by ExamSmasher`,
  );
  lines.push("");
  lines.push(
    "> Each link opens YouTube's own results page for that topic. Nothing here was ranked or " +
      "fetched from YouTube — pick the video that matches your syllabus.",
  );
  lines.push("");

  const byChapter = new Map<string, Topic[]>();
  for (const topic of topics) {
    const key = topic.chapter || "General";
    const bucket = byChapter.get(key) ?? [];
    bucket.push(topic);
    byChapter.set(key, bucket);
  }

  for (const [chapter, chapterTopics] of byChapter) {
    lines.push(`## ${chapter}`);
    lines.push("");
    for (const topic of chapterTopics) {
      const result = results[topic.id];
      const searches = linksFor(result);
      const studied = isStudied(topic.title);

      lines.push(`### ${studied ? "✅ " : ""}${topic.title}`);
      lines.push(
        `\`${topic.importance}\` · \`${topic.difficulty}\` · ~${topic.estimatedMinutes} min${
          studied ? " · **already studied**" : ""
        }`,
      );
      if (topic.description) lines.push("", topic.description);
      lines.push("");

      if (result?.skipped) {
        lines.push("_Skipped — the student has already studied this topic._", "");
        continue;
      }
      if (result?.error) {
        lines.push(`_Could not build search links: ${result.error}_`, "");
        continue;
      }
      if (searches.length === 0) {
        lines.push("_No search link could be built for this topic._", "");
        continue;
      }

      lines.push("| # | Search | Query |");
      lines.push("|---|--------|-------|");
      searches.forEach((s, index) => {
        lines.push(`| ${index + 1} | [${s.label}](${s.url}) | \`${escapeCell(s.query)}\` |`);
      });
      lines.push("");
    }
  }

  const picks = topics
    .filter((t) => !isStudied(t.title) && linksFor(results[t.id]).length > 0)
    .slice(0, 12);
  if (picks.length > 0) {
    lines.push("## 🚀 Quick start — one search per pending topic");
    lines.push("");
    picks.forEach((t) =>
      lines.push(`- [${t.title}](${linksFor(results[t.id])[0].url})`),
    );
    lines.push("");
  }

  return lines.join("\n");
}

export function buildCsv(
  topics: Topic[],
  results: Record<string, TopicResult>,
  isStudied: StudiedPredicate = () => false,
): string {
  const rows: string[] = [
    ["Topic", "Chapter", "Importance", "Difficulty", "Studied", "Link label", "Query", "URL"]
      .map(csvCell)
      .join(","),
  ];

  for (const topic of topics) {
    const searches = linksFor(results[topic.id]);
    const studied = isStudied(topic.title) ? "yes" : "";

    if (searches.length === 0) {
      rows.push(
        [topic.title, topic.chapter ?? "", topic.importance, topic.difficulty, studied, "", "", ""]
          .map(csvCell)
          .join(","),
      );
      continue;
    }

    for (const search of searches) {
      rows.push(
        [
          topic.title,
          topic.chapter ?? "",
          topic.importance,
          topic.difficulty,
          studied,
          search.label,
          search.query,
          search.url,
        ]
          .map(csvCell)
          .join(","),
      );
    }
  }

  return rows.join("\n");
}

function csvCell(value: string): string {
  const escaped = String(value ?? "").replace(/"/g, '""');
  return `"${escaped}"`;
}

function escapeCell(value: string): string {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function downloadFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const area = document.createElement("textarea");
      area.value = text;
      area.style.position = "fixed";
      area.style.opacity = "0";
      document.body.appendChild(area);
      area.select();
      const ok = document.execCommand("copy");
      area.remove();
      return ok;
    } catch {
      return false;
    }
  }
}
