import type { Topic, TopicResult } from "./types";
import { videoUrl } from "./format";

function durationLabel(seconds: number): string {
  if (!seconds) return "—";
  const m = Math.round(seconds / 60);
  return m >= 60 ? `${Math.floor(m / 60)}h ${m % 60}m` : `${m} min`;
}

function pickList(
  topics: Topic[],
  results: Record<string, TopicResult>,
): Array<{ title: string; videoTitle: string; videoUrl: string; seconds: number }> {
  return topics
    .map((t) => {
      const video = results[t.id]?.videos?.[0];
      if (!video) return null;
      return {
        title: t.title,
        videoTitle: video.video.title,
        videoUrl: videoUrl(video.video.id),
        seconds: video.video.durationSeconds,
      };
    })
    .filter((p): p is NonNullable<typeof p> => p !== null);
}

export function totalWatchSeconds(
  topics: Topic[],
  results: Record<string, TopicResult>,
): number {
  return pickList(topics, results).reduce((sum, p) => sum + p.seconds, 0);
}

type StudiedPredicate = (title: string) => boolean;

export function buildMarkdown(
  subject: string,
  topics: Topic[],
  results: Record<string, TopicResult>,
  isStudied: StudiedPredicate = () => false,
): string {
  const lines: string[] = [];
  const matched = topics.filter((t) => (results[t.id]?.videos?.length ?? 0) > 0).length;
  const doneCount = topics.filter((t) => isStudied(t.title)).length;
  const left = topics.length - doneCount;

  lines.push(`# 🎬 ${subject} — Best Video Study List`);
  lines.push("");
  lines.push(
    `> ${matched}/${topics.length} topics matched · ${doneCount}/${topics.length} already studied · ${left} to go · ~${durationLabel(
      totalWatchSeconds(topics, results),
    )} of video remaining · generated by ExamSmasher`,
  );
  lines.push("");

  const byChapter = new Map<string, Topic[]>();
  for (const topic of topics) {
    const key = topic.chapter || "General";
    const bucket = byChapter.get(key) ?? [];
    bucket.push(topic);
    byChapter.set(key, bucket);
  }

  for (const [chapter, chapterTopics] of byChapter) {
    lines.push(`## ${chapter}`);
    lines.push("");
    for (const topic of chapterTopics) {
      const result = results[topic.id];
      const videos = result?.videos ?? [];
      const studied = isStudied(topic.title);

      lines.push(`### ${studied ? "✅ " : ""}${topic.title}`);
      lines.push(
        `\`${topic.importance}\` · \`${topic.difficulty}\` · ~${topic.estimatedMinutes} min${
          studied ? " · **already studied**" : ""
        }`,
      );
      if (topic.description) lines.push("", topic.description);
      lines.push("");

      if (result?.skipped) {
        lines.push("_Skipped — the student has already studied this topic._", "");
        continue;
      }
      if (result?.error) {
        lines.push(`_Search failed: ${result.error}_`, "");
        continue;
      }
      if (videos.length === 0) {
        lines.push("_No strong match found — try rephrasing this topic._", "");
        continue;
      }

      lines.push("| # | Video | Channel | Length | Score | Why it's good |");
      lines.push("|---|-------|---------|--------|-------|---------------|");
      videos.forEach((v, index) => {
        const link = `[${escapeCell(v.video.title)}](${videoUrl(v.video.id)})`;
        lines.push(
          `| ${index + 1} | ${link} | ${escapeCell(v.video.channelTitle)} | ${durationLabel(
            v.video.durationSeconds,
          )} | ${v.score}${v.rank === 1 ? " ⭐" : ""} | ${escapeCell(v.reasons.join("; "))} |`,
        );
      });
      lines.push("");
    }
  }

  const picks = pickList(topics, results).filter((p) => !isStudied(p.title));
  if (picks.length > 0) {
    lines.push("## 🚀 Quick start — one best video per pending topic");
    lines.push("");
    picks.forEach((p) => lines.push(`- [${p.title}](${p.videoUrl}) — ${durationLabel(p.seconds)}`));
    lines.push("");
  }

  return lines.join("\n");
}

export function buildCsv(
  topics: Topic[],
  results: Record<string, TopicResult>,
  isStudied: StudiedPredicate = () => false,
): string {
  const rows: string[] = [
    ["Topic", "Chapter", "Importance", "Difficulty", "Studied", "Rank", "Video Title", "URL", "Channel", "Minutes", "Score", "Reasons"]
      .map(csvCell)
      .join(","),
  ];

  for (const topic of topics) {
    const videos = results[topic.id]?.videos ?? [];
    const studied = isStudied(topic.title) ? "yes" : "";
    if (videos.length === 0) {
      rows.push(
        [topic.title, topic.chapter ?? "", topic.importance, topic.difficulty, studied, "", "", "", "", "", "", ""]
          .map(csvCell)
          .join(","),
      );
      continue;
    }
    for (const v of videos) {
      rows.push(
        [
          topic.title,
          topic.chapter ?? "",
          topic.importance,
          topic.difficulty,
          studied,
          String(v.rank),
          v.video.title,
          videoUrl(v.video.id),
          v.video.channelTitle,
          String(Math.round(v.video.durationSeconds / 60)),
          String(v.score),
          v.reasons.join("; "),
        ]
          .map(csvCell)
          .join(","),
      );
    }
  }

  return rows.join("\n");
}

function csvCell(value: string): string {
  const escaped = String(value ?? "").replace(/"/g, '""');
  return `"${escaped}"`;
}

function escapeCell(value: string): string {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function downloadFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const area = document.createElement("textarea");
      area.value = text;
      area.style.position = "fixed";
      area.style.opacity = "0";
      document.body.appendChild(area);
      area.select();
      const ok = document.execCommand("copy");
      area.remove();
      return ok;
    } catch {
      return false;
    }
  }
}
